#!/usr/bin/env python3
"""Write RESULTS.md (every number in the paper, as markdown tables) from a report folder.

    python scripts/make_results_md.py results/loo_seed42/report RESULTS.md
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

rep = Path(sys.argv[1])
out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path("RESULTS.md")
ANALYTES = ["Clinical", "SNV", "INDEL", "CNV", "RNA", "RNA_Fusion", "Pathology",
            "Plasma_Protein", "Plasma_Lipid", "Tissue_Protein", "Multiomic"]
PIPES = ["P1", "P2", "P3", "P4", "P5", "P6"]
NAMES = {"P1": "P1 L1+SMOTE+RF", "P2": "P2 RFECV+XGBoost", "P3": "P3 Stacking",
         "P4": "P4 t-test+SMOTE+RF", "P5": "P5 L1+NearMiss+RF", "P6": "P6 LightGBM DART"}


def read(name):
    f = rep / f"{name}.csv"
    return pd.read_csv(f) if f.exists() else None


def md(df, floatfmt="{:.3f}"):
    cols = list(df.columns)
    lines = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        cells = []
        for v in row:
            if isinstance(v, (float, np.floating)):
                cells.append("" if not np.isfinite(v) else floatfmt.format(v))
            elif isinstance(v, (bool, np.bool_)):
                cells.append("yes" if v else "no")
            else:
                cells.append(str(v).replace("_", " "))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


info = json.loads((rep / "run_info.json").read_text())
cv = json.loads((rep.parent / "cv_scheme.json").read_text()) if (rep.parent / "cv_scheme.json").exists() else {}
M = read("metrics_long")
seeds = sorted(M[M.labels == "moesm3"].seed.unique()) if M is not None else []
S = []
S.append(f"# Results: {rep.parent.name}\n")
S.append(f"Generated by `scripts/make_results_md.py` from `{rep}`. Every number below "
         "comes from saved per-patient predictions; nothing is typed in.\n")
S.append("| Run setting | Value |\n|---|---|")
S.append(f"| Cross-validation | {'leave-one-patient-out' if cv.get('cv') == 'loo' else cv} |")
S.append(f"| Seeds run | {', '.join(map(str, seeds))} (primary: {seeds[0] if seeds else '-'}) |")
S.append(f"| Pipeline version | {info['version']} |")
S.append(f"| Python / scikit-learn | {info['python']} / {info['packages'].get('sklearn')} |")
S.append(f"| xgboost / lightgbm / imbalanced-learn | {info['packages'].get('xgboost')} / "
         f"{info['packages'].get('lightgbm')} / {info['packages'].get('imblearn')} |")
S.append("| Balanced accuracy (BA) | (sensitivity + specificity) / 2; all-deceased prediction = 0.500 |")
S.append("| Accuracy (ACC) | (TP + TN) / n; the metric of the published Table 1 |\n")

t1 = read("table1_dataset")
S.append("## Table 1. Dataset and the published Table 1 re-expressed\n")
S.append("Published accuracy and balanced accuracy are computed from the published "
         "confusion matrices (TP, FP, TN, FN) of Osipov et al. Table 1. `majority ACC` is "
         "the accuracy of predicting every patient deceased.\n")
t1["majority_ACC"] = t1.n_dead / t1.n
S.append(md(t1[["Analyte", "p", "n", "n_dead", "n_alive", "majority_ACC", "Published_ACC", "Published_BA"]]) + "\n")

t2 = read("table2_reproduction")
if t2 is not None:
    S.append("## Table 2. Reproduction: released classifiers vs the published Table 1\n")
    S.append("Seven released models, fixed seed, run on MOESM3. `best of 7 ACC` picks the model "
             "with the highest held-out accuracy per analyte, which is how the published table was "
             "built (optimistic). `closest model` is the model whose confusion matrix is nearest "
             "(L1 distance in patients) to the published one; distance 0 is an exact match. "
             "`Step 2 nested` picks the model per fold from inner-CV scores only (fair).\n")
    t = t2.rename(columns={"best_of7_ACC_optimistic": "best of 7 ACC", "best_of7_model": "best model",
                           "best_of7_BA_at_that_model": "BA of best", "closest_model": "closest model",
                           "closest_cm_L1_distance": "distance (patients)", "any_exact_match": "exact match",
                           "Step2_nested_ACC": "Step 2 nested ACC", "Step2_nested_BA": "Step 2 nested BA",
                           "majority_ACC": "majority ACC", "pub_ACC": "published ACC", "pub_BA": "published BA"})
    t["ACC gap vs published"] = t["best of 7 ACC"] - t["published ACC"]
    S.append(md(t[["Analyte", "n", "majority ACC", "published ACC", "published BA", "best of 7 ACC",
                   "ACC gap vs published", "best model", "BA of best", "closest model",
                   "distance (patients)", "exact match", "Step 2 nested ACC", "Step 2 nested BA"]]) + "\n")
    bm = read("table2_reproduction_by_model")
    if bm is not None:
        S.append("### Table 2b. Every released model on the multi-omic analyte (n = 39)\n")
        b = bm[bm.Analyte == "Multiomic"]
        cols = ["Method", "ACC", "BA", "TP", "FP", "TN", "FN", "cm_L1_distance"]
        if "ACC_seed_min" in b and b.n_seeds.max() > 1:
            cols += ["n_seeds", "ACC_seed_min", "ACC_seed_max", "BA_seed_min", "BA_seed_max"]
        S.append(md(b[cols]))
        pub = b.iloc[0]
        S.append(f"\nPublished multi-omic row: TP {pub.pub_TP}, FP {pub.pub_FP}, TN {pub.pub_TN}, "
                 f"FN {pub.pub_FN} (ACC {pub.pub_ACC:.3f}, BA {pub.pub_BA:.3f}).\n")
        S.append("### Table 2c. Every released model, every analyte\n")
        cols = ["Analyte", "Method", "ACC", "BA", "TP", "FP", "TN", "FN", "pub_ACC", "cm_L1_distance"]
        S.append(md(bm[cols]) + "\n")

t3 = read("table3_step2_vs_step3")
if t3 is not None:
    S.append("## Table 3. Step 2 (released models) vs Step 3 (fold-internal pipelines), balanced accuracy\n")
    S.append("Both steps select the model per outer fold by inner-CV balanced accuracy on the training "
             "patients. `delta` is Step 3 minus Step 2 with a paired stratified bootstrap 95% interval "
             "and an exact McNemar p (exploratory at these sample sizes). The last row's interval is a "
             "bootstrap over analytes.\n")
    S.append(md(t3) + "\n")
    P = read("stats_portfolio")
    if P is not None:
        S.append("### Table 3b. Each pipeline against Step 2 across the 11 analytes\n")
        P = P.assign(Method=P.Method.map(lambda m: NAMES.get(m, "Step 3 nested best of 6")))
        S.append(md(P[["Method", "mean_delta", "mean_lo", "mean_hi", "wins", "ties", "losses",
                       "sign_p", "wilcoxon_p", "wilcoxon_p_holm_over_P1_P6", "mean_cohens_h"]]) + "\n")
    F = read("stats_friedman")
    if F is not None:
        S.append("### Table 3c. Friedman test over seven treatments (Step 2 + P1–P6), 11 analytes as blocks\n")
        S.append(md(F[["metric", "blocks", "treatments", "chi2", "df", "p", "kendall_W"]]) + "\n")

t4 = read("table4_multiomic")
if t4 is not None:
    S.append("## Table 4. Discrimination on the multi-omic analyte (n = 39, 28 deceased)\n")
    S.append("AUC with bootstrap 95% interval. `RFE_RF` is the released RFECV + random forest.\n")
    S.append(md(t4.assign(Method=t4.Method.map(lambda m: NAMES.get(m, m)))) + "\n")
    t4a = read("table4_discrimination_all")
    if t4a is not None:
        S.append("### Table 4b. AUC of every pipeline on every analyte\n")
        piv = t4a[t4a.Method.isin(PIPES)].pivot(index="Analyte", columns="Method", values="AUC")
        piv = piv.reindex([a for a in ANALYTES if a in piv.index]).reset_index()
        S.append(md(piv) + "\n")

t5 = read("table5_ablation")
if t5 is not None:
    S.append("## Table 5. Ablation on every analyte\n")
    S.append("TN = alive patients correctly identified (out of `n alive`). `all deceased` marks a "
             "run that predicted every patient deceased.\n")
    ba = t5.pivot(index="Analyte", columns="Config", values="BA").reindex(ANALYTES)
    tn = t5.pivot(index="Analyte", columns="Config", values="TN").reindex(ANALYTES)
    na = t5.groupby("Analyte").n_alive.first().reindex(ANALYTES)
    comb = pd.DataFrame({"Analyte": ANALYTES, "n alive": na.values})
    for c in ba.columns:
        comb[c] = [f"{b:.3f} (TN {t:.0f})" for b, t in zip(ba[c], tn[c])]
    S.append(md(comb) + "\n")

ss = read("seed_sensitivity")
if ss is not None:
    S.append("## Table 6. Seed sensitivity (balanced accuracy over seeds)\n")
    S.append(md(ss) + "\n")

nc = read("null_check")
if nc is not None:
    S.append("## Table 7. Permutation null\n")
    S.append(md(nc) + "\n")

fs = read("feature_stability")
if fs is not None:
    S.append("## Table 8. Feature selection stability across folds\n")
    S.append("`mean pairwise jaccard` of the selected feature sets between folds; `in every fold` "
             "counts features selected in all folds.\n")
    S.append(md(fs[["Analyte", "Method", "mean_selected", "mean_pairwise_jaccard", "in_every_fold"]]) + "\n")
    S.append("Most frequently selected features (fraction of folds):\n")
    for r in fs[fs.Method.isin(["P1", "P5", "L1_RF"])].itertuples():
        S.append(f"- **{r.Analyte} / {r.Method}**: {r.top_features}")
    S.append("")

rt = read("runtime_by_method")
if rt is not None:
    S.append("## Runtime\n")
    S.append(md(rt[~rt.Method.str.contains("@")], "{:.2f}") + "\n")

S.append("## Figures\n")
for f in sorted(rep.glob("*.png")):
    S.append(f"- `{f.relative_to(rep.parent.parent)}`")
out.write_text("\n".join(S) + "\n")
print(f"wrote {out} ({len(S)} blocks)")
